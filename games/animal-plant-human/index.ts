export function getDictionaryWords(letter: string, category: Category): string[] {
  const normLetter = letter.replace(/[أإآ]/g, "أ");
  const dict = ARABIC_WORDS[normLetter] || ARABIC_WORDS["أ"];

  switch (category) {
    case "إنسان":
      return dict.names;
    case "نبات":
      return dict.plants;
    case "حيوان":
      return dict.animals;
    case "جماد":
      return dict.objects;
    case "بلاد":
      return dict.countries;
  }
}
